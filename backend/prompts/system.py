# ★ 为什么需要这个阶段？
#   没有它的时候，REFLECT 一旦判定 done=true，Agent 就直接用
#   「任务已完成（第 N 轮，共观测 M 条事实）」这种**程序生成的进度模板**收尾。
#   那对 Agent 内部是有意义的记账，但**没有回答用户的问题** ——
#   用户问「分析当前项目结构」，得到的却是一份工具调用清单。
#
#   进度清单回答的是「你做了什么」，而不是「你发现了什么」。
#   这两件事必须分开：
#     · 进度清单 → 由程序生成（Agent 的记账，已由 task.end / 运行摘要承担）
#     · 最终答复 → 由模型生成（基于已观测到的证据作答）
#
#   所以新增这个阶段：在做完所有工具调用后，**再多问模型一次**，
#   明确要求它「基于已观测到的内容，直接回答用户的原始任务」。
#   这次调用不带 tools —— 强制它收口成答案，而不是又去调工具。
